CREATE DATABASE IF NOT EXISTS ladle_loan_db CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE ladle_loan_db;
CREATE TABLE IF NOT EXISTS users (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 full_name VARCHAR(100) NOT NULL,
 email VARCHAR(190) NOT NULL UNIQUE,
 phone VARCHAR(20) NOT NULL,
 password_hash VARCHAR(255) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS admins (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 username VARCHAR(60) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS applications (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 reference_no VARCHAR(24) NOT NULL UNIQUE,
 user_id INT UNSIGNED NOT NULL,
 loan_type ENUM('Personal Loan','Home Loan','Education Loan') NOT NULL,
 amount DECIMAL(12,2) NOT NULL,
 tenure_years TINYINT UNSIGNED NOT NULL,
 purpose VARCHAR(500) NOT NULL,
 status ENUM('Submitted','Under Review','Approved','Rejected') NOT NULL DEFAULT 'Submitted',
 admin_note VARCHAR(500) NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_app_user FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
 INDEX idx_app_status(status), INDEX idx_app_reference(reference_no)
);